    private static boolean ignored(ResourceLocation key) {
        return key.toString().startsWith("hbm:item.ammo_") || nativeIgnored.contains(key);
    }
    @SubscribeEvent
    public static void missingBlocks(RegistryEvent.MissingMappings<Block> event) {
        prepareMappings();
        for(RegistryEvent.MissingMappings.Mapping<Block> mapping : event.getAllMappings()) {
            if(ignored(mapping.key)) mapping.ignore();
        }
    }
    @SubscribeEvent
    public static void missingItems(RegistryEvent.MissingMappings<Item> event) {
        prepareMappings();
        for(RegistryEvent.MissingMappings.Mapping<Item> mapping : event.getAllMappings()) {
            if(ignored(mapping.key)) { mapping.ignore(); continue; }
            Item target=remapItems.get(mapping.key.toString());
            if(target!=null) mapping.remap(target);
        }
    }
